CREATE TABLE `generated_artifacts` (
  `id` INTEGER NOT NULL AUTO_INCREMENT,
  `owner_user_id` INTEGER NOT NULL,
  `agent_id` INTEGER NOT NULL,
  `conversation_id` INTEGER NOT NULL,
  `task_id` INTEGER NULL,
  `operation_id` VARCHAR(64) NOT NULL,
  `artifact_type` VARCHAR(32) NOT NULL,
  `title` VARCHAR(200) NOT NULL,
  `description` TEXT NULL,
  `course_id` INTEGER NULL,
  `knowledge_point_ids_json` JSON NULL,
  `requirements_json` JSON NOT NULL,
  `content_schema_json` JSON NULL,
  `preview_html` LONGTEXT NULL,
  `file_format` VARCHAR(16) NOT NULL DEFAULT 'DOCX',
  `storage_path` VARCHAR(1000) NULL,
  `file_size_bytes` BIGINT NULL,
  `status` ENUM('DRAFT','GENERATING','CONTENT_READY','EXPORTING','READY','FAILED','EXPIRED','DELETING','DELETED') NOT NULL DEFAULT 'DRAFT',
  `error_code` VARCHAR(100) NULL,
  `last_accessed_at` DATETIME(3) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  `deleted_at` DATETIME(3) NULL,
  UNIQUE INDEX `generated_artifacts_task_id_key`(`task_id`),
  UNIQUE INDEX `generated_artifacts_owner_conversation_operation_key`(`owner_user_id`,`conversation_id`,`operation_id`),
  INDEX `generated_artifacts_owner_user_id_status_updated_at_idx`(`owner_user_id`,`status`,`updated_at`),
  INDEX `generated_artifacts_agent_id_idx`(`agent_id`),
  INDEX `generated_artifacts_conversation_id_idx`(`conversation_id`),
  INDEX `generated_artifacts_course_id_idx`(`course_id`),
  PRIMARY KEY (`id`),
  CONSTRAINT `generated_artifacts_owner_user_id_fkey` FOREIGN KEY (`owner_user_id`) REFERENCES `users`(`user_id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `generated_artifacts_agent_id_fkey` FOREIGN KEY (`agent_id`) REFERENCES `user_agents`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `generated_artifacts_conversation_id_fkey` FOREIGN KEY (`conversation_id`) REFERENCES `agent_market_conversations`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `generated_artifacts_task_id_fkey` FOREIGN KEY (`task_id`) REFERENCES `async_tasks`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `generated_artifacts_course_id_fkey` FOREIGN KEY (`course_id`) REFERENCES `courses`(`course_id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
