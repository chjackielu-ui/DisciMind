CREATE TABLE `teacher_reminders` (
  `id` INTEGER NOT NULL AUTO_INCREMENT,
  `teacher_user_id` INTEGER NOT NULL,
  `title` VARCHAR(200) NOT NULL,
  `description` TEXT NULL,
  `reminder_type` VARCHAR(40) NOT NULL DEFAULT 'manual',
  `priority` VARCHAR(20) NOT NULL DEFAULT 'normal',
  `course_id` INTEGER NULL,
  `teaching_class_id` INTEGER NULL,
  `business_type` VARCHAR(50) NULL,
  `business_id` INTEGER NULL,
  `start_at` DATETIME(3) NOT NULL,
  `remind_at` DATETIME(3) NOT NULL,
  `end_at` DATETIME(3) NULL,
  `recurrence_rule` JSON NULL,
  `advance_minutes` INTEGER NOT NULL DEFAULT 0,
  `status` VARCHAR(20) NOT NULL DEFAULT 'pending',
  `snoozed_until` DATETIME(3) NULL,
  `completed_at` DATETIME(3) NULL,
  `dismissed_at` DATETIME(3) NULL,
  `notes` TEXT NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  INDEX `teacher_reminders_teacher_user_id_status_remind_at_idx` (`teacher_user_id`, `status`, `remind_at`),
  INDEX `teacher_reminders_course_id_teaching_class_id_idx` (`course_id`, `teaching_class_id`),
  INDEX `teacher_reminders_business_type_business_id_idx` (`business_type`, `business_id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
