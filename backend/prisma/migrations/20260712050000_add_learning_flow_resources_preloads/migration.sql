  CONSTRAINT `lf_resource_artifact_fkey` FOREIGN KEY (`artifact_id`) REFERENCES `generated_artifacts`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `lf_resource_course_fkey` FOREIGN KEY (`course_id`) REFERENCES `courses`(`course_id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `lf_resource_kp_fkey` FOREIGN KEY (`knowledge_point_id`) REFERENCES `knowledge_points`(`knowledge_point_id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `lf_resource_goal_fkey` FOREIGN KEY (`learning_goal_id`) REFERENCES `learning_goals`(`goal_id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `lf_resource_template_fkey` FOREIGN KEY (`workflow_template_id`) REFERENCES `learning_workflow_templates`(`template_id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `lf_resource_session_fkey` FOREIGN KEY (`learning_session_id`) REFERENCES `learning_sessions`(`session_id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

